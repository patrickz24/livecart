-- Least-privilege grants, applied by init-roles.sh inside each LiveCart
-- database (livecart and livecart_test), after roles.sql.
-- psql variable: db, the current database name.

\set ON_ERROR_STOP on

-- Only livecart_app may connect besides the owner (livecart_migrator); no
-- other role gets CONNECT, and nobody gets TEMPORARY.
REVOKE ALL ON DATABASE :"db" FROM PUBLIC;
GRANT CONNECT ON DATABASE :"db" TO livecart_app;

-- Only the database owner creates objects in the public schema.
REVOKE ALL ON SCHEMA public FROM PUBLIC;
GRANT USAGE ON SCHEMA public TO livecart_app;

-- Every table the migrator creates from now on: read and write rows, never
-- DELETE, TRUNCATE, ALTER or DROP. Primary keys are UUIDs generated by the
-- application, so no sequence privilege is needed.
ALTER DEFAULT PRIVILEGES FOR ROLE livecart_migrator IN SCHEMA public
    GRANT SELECT, INSERT, UPDATE ON TABLES TO livecart_app;

-- Tables that already exist when the script is re-run by hand.
GRANT SELECT, INSERT, UPDATE ON ALL TABLES IN SCHEMA public TO livecart_app;

-- Except the migration history, which only the migrator reads and writes
-- (the baseline revision revokes the default privileges above on it). The
-- grant above gave them back if the table already exists.
DO $$
BEGIN
    IF to_regclass('public.alembic_version') IS NOT NULL THEN
        REVOKE ALL ON TABLE public.alembic_version FROM livecart_app;
    END IF;
END
$$;
