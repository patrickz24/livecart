products: Final = sa.Table(
    "products",
    metadata,
    _id(),
    sa.Column("session_id", sa.Uuid, sa.ForeignKey("live_sessions.id"), nullable=False),
    sa.Column("code", sa.String(7), nullable=False),
    # '' rather than NULL for "no variant": the unique index below would let
    # two NULL variants of one code through.
    sa.Column("variant", sa.String(MAX_VARIANT_LENGTH), nullable=False, server_default=""),
    sa.Column("name", sa.String(200), nullable=False),
    sa.Column("price_minor", sa.BigInteger, nullable=False),
    sa.Column("stock_total", sa.Integer, nullable=False),
    sa.Column("reserved", sa.Integer, nullable=False, server_default="0"),
    sa.Column("sold", sa.Integer, nullable=False, server_default="0"),
    # Computed by PostgreSQL on every write, so that the reservation compares
    # one column and no code path can let it drift from the counters.
    sa.Column(
        "available",
        sa.Integer,
        sa.Computed(
            sa.column("stock_total", sa.Integer)
            - sa.column("reserved", sa.Integer)
            - sa.column("sold", sa.Integer),
            persisted=True,
        ),
        nullable=False,
    ),
    _created_at(),
    _updated_at(),
    sa.UniqueConstraint(
        "session_id", "code", "variant", name="uq_products_session_id_code_variant"
    ),
    sa.CheckConstraint(
        sa.column("code", sa.String).regexp_match(f"^{PRODUCT_CODE_PATTERN.pattern}$"),
        name="ck_products_code",
    ),
    # The invariant the reservation relies on: nothing is ever oversold.
    sa.CheckConstraint(
        sa.and_(
            sa.column("reserved", sa.Integer) >= 0,
            sa.column("sold", sa.Integer) >= 0,
            sa.column("reserved", sa.Integer) + sa.column("sold", sa.Integer)
            <= sa.column("stock_total", sa.Integer),
        ),
        name="ck_products_stock",
    ),
    _at_least("price_minor", 0, name="ck_products_price_minor"),
)


