# --- Orders, payments and shipments ----------------------------------------------------

orders: Final = sa.Table(
    "orders",
    metadata,
    _id(),
    sa.Column("reference", sa.CHAR(REFERENCE_LENGTH), nullable=False),
    # SHA-256 of the order's access token (livecart_core.order_tokens); the
    # token is recomputed from the order id, never stored.
    sa.Column("access_token_hash", sa.LargeBinary, nullable=False),
    sa.Column("seller_id", sa.Uuid, sa.ForeignKey("sellers.id"), nullable=False),
    sa.Column("session_id", sa.Uuid, sa.ForeignKey("live_sessions.id"), nullable=False),
    sa.Column("intent_id", sa.Uuid, sa.ForeignKey("purchase_intents.id"), nullable=False),
    sa.Column("product_id", sa.Uuid, sa.ForeignKey("products.id"), nullable=False),
    sa.Column("quantity", sa.Integer, nullable=False),
    sa.Column("unit_price_minor", sa.BigInteger, nullable=False),
    sa.Column("total_minor", sa.BigInteger, nullable=False),
    sa.Column("currency", sa.CHAR(3), nullable=False),
    sa.Column(
        "status", sa.String(20), nullable=False, server_default=OrderStatus.PENDING_PAYMENT.value
    ),
    # The reservation the order carries, and the lease of the expiry sweep
    # while it asks the payment provider to expire a session (milestone 5).
    _timestamp("reserved_until", nullable=False),
    _timestamp("expiry_lease_until"),
    _identifier("buyer_platform_user_id"),
    _timestamp("buyer_notified_at"),
    sa.Column("shipping_address", postgresql.JSONB, nullable=True),
    _timestamp("paid_at"),
    _timestamp("expired_at"),
    _created_at(),
    _updated_at(),
    sa.UniqueConstraint("reference", name="uq_orders_reference"),
    sa.UniqueConstraint("intent_id", name="uq_orders_intent_id"),
    sa.CheckConstraint(
        sa.column("reference", sa.CHAR).regexp_match(
            f"^{REFERENCE_PREFIX}[{CROCKFORD_ALPHABET}]{{{REFERENCE_SYMBOLS}}}$"
        ),
        name="ck_orders_reference",
    ),
    _sha256("access_token_hash", name="ck_orders_access_token_hash"),
    _quantity("orders"),
    _at_least("unit_price_minor", 0, name="ck_orders_unit_price_minor"),
    sa.CheckConstraint(
        sa.column("total_minor", sa.BigInteger)
        == sa.column("unit_price_minor", sa.BigInteger) * sa.column("quantity", sa.Integer),
        name="ck_orders_total_minor",
    ),
    _currency("orders"),
    _one_of("status", OrderStatus, name="ck_orders_status"),
    # A buyer holds at most one pending order per product of a session: the
    # reservation turns a second one into an already_reserved intent.
    sa.Index(
        "uq_orders_pending_buyer_product",
        "session_id",
        "product_id",
        "buyer_platform_user_id",
        unique=True,
        postgresql_where=sa.column("status", sa.String) == OrderStatus.PENDING_PAYMENT.value,
    ),
    # What the expiry sweep scans.
    sa.Index(
        "ix_orders_pending_reserved_until",
        "reserved_until",
        postgresql_where=sa.column("status", sa.String) == OrderStatus.PENDING_PAYMENT.value,
    ),
    # The dashboard's orders of a session.
    sa.Index("ix_orders_session_id", "session_id"),
)

