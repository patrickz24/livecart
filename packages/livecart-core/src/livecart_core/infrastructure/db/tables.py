    sa.Column("llm_latency_ms", sa.Integer, nullable=True),
    _created_at(),
    _updated_at(),
    # The deduplication of every delivery of one platform comment.
    sa.UniqueConstraint(
        "platform", "external_comment_id", name="uq_comments_platform_external_comment_id"
    ),
    _one_of("platform", Platform, name="ck_comments_platform"),
