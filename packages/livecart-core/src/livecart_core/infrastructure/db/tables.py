"""The database schema as SQLAlchemy Core tables: what the adapters query and the migrations build.

This metadata is the single description of the schema. The Alembic revisions
are written by hand (a revision must keep building the schema of its day, so
it never imports this module), and an integration test builds this metadata
in a scratch schema and compares it, catalog entry by catalog entry, with
what ``livecart-migrate upgrade head`` built: a revision that drifts from the
tables below fails CI. ``alembic revision --autogenerate`` also reads this
metadata (``migrations/env.py``) to draft the next revision.

Conventions of the plan's data model:

- primary keys are UUID v7, generated by the application (``ids.new_id``),
  so that ids sort by creation time and no sequence privilege is needed;
- amounts are integer minor units in ``BIGINT`` columns checked ``>= 0``, and
  the currency is frozen on the order and the payment;
- every closed list (statuses, platforms, providers, reasons) is a
  ``VARCHAR`` with a named ``CHECK`` built from the enum that the domain or
  the application layer defines, so that a value added in code without a
  migration fails the schema comparison test;
- timestamps are ``timestamptz``; every table has ``id`` and ``created_at``,
  plus ``updated_at`` when its rows change, which every Core ``update()``
  sets through ``onupdate``;
- every constraint and index carries an explicit name, the plan's own when it
  gives one, so that an error or a migration can name it.

``livecart_app`` receives SELECT, INSERT and UPDATE on every table through the
default privileges of ``infra/postgres/grants.sql``, never DELETE.
"""

