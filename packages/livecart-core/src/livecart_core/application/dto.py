# --- Idempotent requests ---------------------------------------------------------------

# An Idempotency-Key header: visible ASCII, from "!" to "~" (clients send UUIDs
# or ULIDs), bounded so that it cannot make a store key of any size.
MAX_IDEMPOTENCY_KEY_LENGTH: Final = 255
IDEMPOTENCY_KEY_PATTERN: Final = r"^[!-~]+$"


@dataclass(frozen=True, slots=True)
class IdempotencyKey:
    """An idempotency key as the store knows it: per route (``scope``) and per seller."""

    scope: str
    seller_id: UUID
    value: str

    def __post_init__(self) -> None:
        if not 1 <= len(self.value) <= MAX_IDEMPOTENCY_KEY_LENGTH or not re.fullmatch(
            IDEMPOTENCY_KEY_PATTERN, self.value
        ):
            raise ValueError(
                f"an idempotency key is 1 to {MAX_IDEMPOTENCY_KEY_LENGTH} visible ASCII characters"
            )
        if not re.fullmatch(r"[a-z][a-z-]*", self.scope):
            raise ValueError(f"{self.scope!r} is not an idempotency scope")


