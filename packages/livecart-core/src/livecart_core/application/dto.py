class QueuedComment(BaseModel):
    """The queue envelope: one comment and the identifiers that follow it to the worker.

    ``correlation_id`` is created at ingestion and repeated in the logs and the
    session events of everything the comment causes; ``request_id`` is the
    ``X-Request-ID`` of the webhook call that carried it; ``enqueued_at``
    measures the time spent in the queue.
    """

    model_config = ConfigDict(extra="forbid", frozen=True)

    comment: IncomingComment
    correlation_id: str = Field(min_length=1, max_length=MAX_IDENTIFIER_LENGTH)
    request_id: str = Field(min_length=1, max_length=MAX_IDENTIFIER_LENGTH)
    enqueued_at: AwareDatetime


@dataclass(frozen=True, slots=True)
class QueueDelivery:
    """One delivery of a queued comment to a consumer; ``delivery_id`` is the queue's own id."""

    delivery_id: str
    comment: QueuedComment
    # 1 on the first delivery, then one more each time the comment is reclaimed.
    delivery_count: int

    def __post_init__(self) -> None:
        if self.delivery_count < 1:
            raise ValueError(f"delivery_count starts at 1, not {self.delivery_count}")


