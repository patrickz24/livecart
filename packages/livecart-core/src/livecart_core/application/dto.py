"""The data that crosses the ports of the application layer.

Two kinds, on purpose:

- pydantic models for the payloads that cross a process or network boundary
  and are validated when they arrive: the common comment webhook format
  (``IncomingComment``, ``CommentBatch``), the queue envelope, the session
  events, a buyer's shipping address and a verified payment event. They are
  frozen, refuse unknown fields and bound every string;
- frozen dataclasses for what the adapters hand back to the use cases (rows
  read from the database, results of an atomic write) and for the requests a
  use case sends to a provider. They hold domain objects (``Money``,
  ``ProductCode``, ``OrderReference``, the statuses) and check their own
  invariants. A record is a snapshot: changing a row is a port call, never an
  assignment.

Identifiers are ``UUID`` values generated by the adapters (UUID v7 in
PostgreSQL, milestone 3), and every timestamp is timezone-aware.
"""

