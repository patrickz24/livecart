@dataclass(frozen=True, slots=True)
class StockLevel:
    """The stock counters of one product, under the invariant of ``ck_products_stock``."""

    total: int
    reserved: int = 0
    sold: int = 0

    def __post_init__(self) -> None:
        if min(self.total, self.reserved, self.sold) < 0 or self.reserved + self.sold > self.total:
            raise ValueError(
                f"stock needs 0 <= reserved + sold <= total, got total={self.total}, "
                f"reserved={self.reserved}, sold={self.sold}"
            )

    @property
    def available(self) -> int:
        """The generated column ``products.available``."""
        return self.total - self.reserved - self.sold


