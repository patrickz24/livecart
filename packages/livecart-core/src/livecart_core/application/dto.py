# --- LLM fallback ----------------------------------------------------------------------


@dataclass(frozen=True, slots=True)
class FallbackRequest:
    """One ambiguous comment for the fallback, what it may read, and how long it has."""

    # The key of the per-session budget; never sent to the model.
    session_id: UUID
    text: str
    ambiguity: Ambiguous
    catalog: Catalog
    # What is left of the message deadline once the fallback slot is taken.
    timeout_seconds: float

    def __post_init__(self) -> None:
        if not self.timeout_seconds > 0:
            raise ValueError(f"timeout_seconds must be positive, not {self.timeout_seconds}")


@dataclass(frozen=True, slots=True)
class LlmProposal:
    """What the model read into an ambiguous comment, as it said it: not trusted yet.

    The domain (``decide_from_llm``, milestone 4c) checks it against the
    catalog before anything is reserved, so a code or a variant here may name
    nothing at all.
    """

    product_code: str
    variant: str
    quantity: int
    confidence: Decimal


@dataclass(frozen=True, slots=True)
class FallbackReceipt:
    """The receipt of one fallback attempt, stored once in the ``comments.llm_*`` columns.

    Only an ``ok`` outcome carries a proposal. The metering fields are what the
    provider reported, ``None`` when no call reached it (disabled, over
    budget, busy).
    """

    outcome: LlmOutcome
    proposal: LlmProposal | None = None
    request_id: str | None = None
    model: str | None = None
    input_tokens: int | None = None
    output_tokens: int | None = None
    latency_ms: int | None = None

    def __post_init__(self) -> None:
        if (self.outcome is LlmOutcome.OK) != (self.proposal is not None):
            raise ValueError("an ok receipt carries a proposal, and only an ok receipt does")


