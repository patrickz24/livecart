class IncomingComment(BaseModel):
    """One live comment in the common webhook format, whatever its platform.

    The simulator's adapter receives this format as is; the other adapters
    build it from their platform's native payload.
    """

    model_config = ConfigDict(extra="forbid", frozen=True)

    platform: Platform
