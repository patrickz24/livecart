# --- Intents and orders ----------------------------------------------------------------


class IntentSource(StrEnum):
    """Who resolved a purchase intent: ``purchase_intents.source``."""

    PARSER = "parser"
    LLM = "llm"


@dataclass(frozen=True, slots=True)
class ResolvedIntent:
    """A purchase intent settled on one product of the session: by the parser, or by the LLM.

    The LLM's proposal becomes one only once the domain has checked it
    against the catalog (``decide_from_llm``).
    """

    product_code: ProductCode
    variant: Variant
    quantity: Quantity
    source: IntentSource
    confidence: Decimal
    # The substrings of the comment the intent rests on.
    evidence: tuple[str, ...]

    def __post_init__(self) -> None:
        if not Decimal(0) <= self.confidence <= Decimal(1):
            raise ValueError(f"confidence must be from 0 to 1, not {self.confidence}")

    @classmethod
    def from_match(cls, match: Match) -> Self:
        """The intent of a parser match, with the confidence of the evidence it relied on."""
        return cls(
            product_code=match.product_code,
            variant=match.variant,
            quantity=match.quantity,
            source=IntentSource.PARSER,
            confidence=match.confidence.value,
            evidence=match.evidence,
        )

    @classmethod
    def from_llm(cls, choice: LlmChoice, *, evidence: tuple[str, ...]) -> Self:
        """The intent of a proposal the domain accepted.

        The model answers no free text, so the evidence is what the parser
        found in the comment before it gave up: the words the ambiguity rests on.
        """
        return cls(
            product_code=choice.product_code,
            variant=choice.variant,
            quantity=choice.quantity,
            source=IntentSource.LLM,
            confidence=choice.confidence,
            evidence=evidence,
        )


@dataclass(frozen=True, slots=True)
class ReservationRequest:
    """Unit 3 of a comment: reserve one resolved intent and open its order."""

    comment_id: UUID
    session_id: UUID
    product_code: ProductCode
    variant: Variant
    quantity: Quantity
    source: IntentSource
    confidence: Decimal
    # The substrings of the comment the intent rests on.
    evidence: tuple[str, ...]
    now: datetime
    # now + RESERVATION_TTL_SECONDS, computed by the use case from its settings.
    reserved_until: datetime
    # What the parser said of the comment, recorded with its settlement; None
    # leaves comments.parse_result as it is.
    parse: ParseSummary | None = None

    def __post_init__(self) -> None:
        if not Decimal(0) <= self.confidence <= Decimal(1):
            raise ValueError(f"confidence must be from 0 to 1, not {self.confidence}")
        if self.reserved_until <= self.now:
            raise ValueError("a reservation must end after it starts")
        if self.parse is not None and self.parse.kind is ParseKind.REJECTED:
            raise ValueError("a comment the parser rejected reserves nothing")


