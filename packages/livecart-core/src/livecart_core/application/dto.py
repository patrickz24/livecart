class AttemptOpeningKind(StrEnum):
    """What asking for a new payment attempt gave."""

    # A new pending attempt, and the reservation extended by the grace period.
    OPENED = "opened"
    # An attempt is already pending: its redirect URL is reused.
    PENDING = "pending"
    # The order no longer waits for a payment, or its reservation has ended.
    NOT_PAYABLE = "not_payable"
    # PAYMENT_MAX_ATTEMPTS attempts were made already.
    EXHAUSTED = "exhausted"


@dataclass(frozen=True, slots=True)
class AttemptOpening:
    """The result of asking for a payment attempt: its kind, and the attempt when there is one."""

    kind: AttemptOpeningKind
    payment: PaymentRecord | None = None

    def __post_init__(self) -> None:
        with_payment = self.kind in (AttemptOpeningKind.OPENED, AttemptOpeningKind.PENDING)
        if with_payment != (self.payment is not None):
            raise ValueError("an opened or pending attempt carries its payment, and only those do")


class CheckoutStatus(StrEnum):
    """The status of a provider's hosted checkout session."""

    OPEN = "open"
    COMPLETE = "complete"
    EXPIRED = "expired"


@dataclass(frozen=True, slots=True)
class CheckoutRequest:
    """A hosted checkout session to create for one payment attempt."""

    order_id: UUID
    attempt_no: int
    reference: OrderReference
    amount: Money
    success_url: str
    cancel_url: str

    def __post_init__(self) -> None:
        if self.attempt_no < 1:
            raise ValueError(f"attempt_no starts at 1, not {self.attempt_no}")

    @property
    def idempotency_key(self) -> str:
        # One key per attempt: a provider refuses a key reused with other
        # parameters, and each attempt checks the amount again.
        return f"checkout-session:{self.order_id}:{self.attempt_no}"


@dataclass(frozen=True, slots=True)
class CheckoutSession:
    """A provider's hosted checkout session, as the provider reports it."""

    provider_ref: str
    redirect_url: str
    status: CheckoutStatus
    amount: Money
    payment_ref: str | None = None


class PaymentEvent(BaseModel):
    """A verified payment webhook, reduced to the fields LiveCart acts on.

    This model is the allow-list of ``processed_webhook_events.payload``:
    anything else the provider sends, the customer's details first, is dropped
    at verification and never stored.
    """

    model_config = ConfigDict(extra="forbid", frozen=True)

    provider: PaymentProviderName
    event_id: str = Field(min_length=1, max_length=255)
    event_type: str = Field(min_length=1, max_length=128)
    checkout_ref: str | None = Field(default=None, min_length=1, max_length=255)
    payment_ref: str | None = Field(default=None, min_length=1, max_length=255)
    amount_minor: int | None = Field(default=None, ge=0)
    currency: str | None = Field(default=None, pattern=r"^[A-Z]{3}$")
    occurred_at: AwareDatetime

    @model_validator(mode="after")
    def _amount_and_currency_together(self) -> Self:
        if (self.amount_minor is None) != (self.currency is None):
            raise ValueError("amount_minor and currency come together")
        return self

    @property
    def amount(self) -> Money | None:
        if self.amount_minor is None or self.currency is None:
            return None
        return Money(self.amount_minor, self.currency)


