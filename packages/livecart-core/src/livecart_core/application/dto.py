@dataclass(frozen=True, slots=True)
class ProductChanges:
    """The fields of a product a seller changes; ``None`` keeps a field as it is.

    The stock is not among them: it only moves by restock deltas, which never
    race the reservations the way setting a total would.
    """

    code: ProductCode | None = None
    variant: Variant | None = None
    name: str | None = None
    price_minor: int | None = None

    def __post_init__(self) -> None:
        if self.name is not None:
            _check_label("a name", self.name, MAX_PRODUCT_NAME_LENGTH)
        if self.price_minor is not None:
            _check_price(self.price_minor)

    def key_of(self, product: ProductRecord) -> tuple[ProductCode, Variant]:
        """The code and variant ``product`` has once changed."""
        return (
            self.code if self.code is not None else product.code,
            self.variant if self.variant is not None else product.variant,
        )

    def touches_keys(self, product: ProductRecord) -> bool:
        """Whether the change moves the code or the variant comments name the product by."""
        return self.key_of(product) != (product.code, product.variant)


