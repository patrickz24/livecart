# The id a session's stream gives each event, as Redis Streams writes it:
# milliseconds, a dash, a sequence number. It is the SSE id a client sends back
# in Last-Event-ID, so it is bounded before anything reads it.
EVENT_ID_PATTERN: Final = re.compile(r"(\d{1,20})-(\d{1,20})")


def event_id_key(event_id: str) -> tuple[int, int]:
    """``1790414357891-0`` as (1790414357891, 0), which sorts as the stream orders its ids."""
    match = EVENT_ID_PATTERN.fullmatch(event_id)
    if match is None:
        raise ValueError(f"{event_id!r} is not an event id (<milliseconds>-<sequence>)")
    return int(match[1]), int(match[2])


@dataclass(frozen=True, slots=True)
class StreamedEvent:
    """An event as its session's stream holds it, under the id the stream gave it."""

    event_id: str
    event: SessionEvent

    def __post_init__(self) -> None:
        event_id_key(self.event_id)


# --- Pages of a list -------------------------------------------------------------------

# The longest page a list answers. Every list is paginated by keyset on the
# UUID v7 ids, which sort by creation: a page never shifts when rows are
# added meanwhile, and the next one starts where the index scan stopped.
MAX_PAGE_SIZE: Final = 100


class Identified(Protocol):
    @property
    def id(self) -> UUID: ...


@dataclass(frozen=True, slots=True)
class Page[T]:
    """One page of a list, and the cursor of the next one: ``None`` on the last page."""

    items: tuple[T, ...]
    next_cursor: UUID | None = None


def check_page_size(limit: int) -> int:
    """A page size from 1 to ``MAX_PAGE_SIZE``; the API bounds it before any adapter sees it."""
    if not 1 <= limit <= MAX_PAGE_SIZE:
        raise ValueError(f"a page holds 1 to {MAX_PAGE_SIZE} items, not {limit}")
    return limit


def page_of[R: Identified](rows: Sequence[R], limit: int) -> Page[R]:
    """The page of ``limit`` items that ``limit + 1`` fetched rows give.

    An adapter fetches one row more than the page holds: when it comes back,
    another page follows, and it starts after the last item of this one.
    """
    items = tuple(rows[:limit])
    return Page(items, items[-1].id if len(rows) > limit else None)


# --- Live sessions and stock -----------------------------------------------------------

# The widths of live_sessions.title and products.name.
MAX_TITLE_LENGTH: Final = 200
MAX_PRODUCT_NAME_LENGTH: Final = 200
# The dearest price a seller may set: times the largest quantity (99), a total
# stays far below 2**53, the largest integer a JavaScript client reads exactly.
MAX_PRICE_MINOR: Final = 100_000_000
# The largest stock total, so far below the INTEGER counters' 2**31 that no
# series of restocks can overflow them.
MAX_STOCK_TOTAL: Final = 1_000_000


def _check_label(what: str, value: str, max_length: int) -> None:
    """A title, a name or an id as the seller typed it once stripped: 1 to ``max_length``."""
    if value != value.strip() or not 1 <= len(value) <= max_length:
        raise ValueError(f"{what} has 1 to {max_length} characters, without surrounding spaces")


def _check_price(price_minor: int) -> None:
    if not 0 <= price_minor <= MAX_PRICE_MINOR:
        raise ValueError(f"a price is from 0 to {MAX_PRICE_MINOR} minor units, not {price_minor}")


