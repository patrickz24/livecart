"""The schema metadata against the plan's data model, without a database.

The integration test ``test_schema.py`` proves that the migrations build this
metadata; these tests prove that the metadata holds what the plan names.
"""

import pytest
import sqlalchemy as sa

from livecart_core.infrastructure.db import tables
from livecart_core.infrastructure.db.tables import metadata

PLAN_TABLES = {
    "sellers",
    "refresh_tokens",
    "live_sessions",
    "products",
    "comments",
    "purchase_intents",
    "orders",
    "payments",
    "processed_webhook_events",
    "shipments",
}

# Every constraint and index the plan's data model names, by table.
PLAN_NAMES = {
    "sellers": {"uq_sellers_email", "uq_sellers_slug"},
    "refresh_tokens": {"uq_refresh_tokens_token_hash", "ix_refresh_tokens_family_id"},
    "live_sessions": {
        "uq_live_sessions_platform_external_live_id",
        "ck_live_sessions_platform",
        "ck_live_sessions_status",
    },
    "products": {"uq_products_session_id_code_variant", "ck_products_code", "ck_products_stock"},
    "comments": {
        "uq_comments_platform_external_comment_id",
        "ck_comments_status",
        "ck_comments_rejection_reason",
    },
    "purchase_intents": {"uq_purchase_intents_comment_id", "ck_purchase_intents_quantity"},
    "orders": {
        "uq_orders_reference",
        "uq_orders_intent_id",
        "ck_orders_status",
        "uq_orders_pending_buyer_product",
    },
    "payments": {
        "uq_payments_order_id_attempt_no",
        "uq_payments_provider_ref",
        "ck_payments_status",
        "uq_payments_order_id_pending",
    },
    "processed_webhook_events": {"uq_processed_webhook_events_provider_event_id"},
    "shipments": {"uq_shipments_order_id", "uq_shipments_tracking_number"},
}

# PostgreSQL truncates longer identifiers, silently.
MAX_IDENTIFIER_BYTES = 63


def _names(table: sa.Table) -> set[str]:
    names = {constraint.name for constraint in table.constraints}
    names |= {index.name for index in table.indexes}
    return {str(name) for name in names if name is not None}


def _partial_index(table: sa.Table, name: str) -> sa.Index:
    index = next(index for index in table.indexes if index.name == name)
    assert index.dialect_options["postgresql"]["where"] is not None
    return index


def test_the_metadata_holds_the_tables_of_the_plan() -> None:
    assert set(metadata.tables) == PLAN_TABLES


@pytest.mark.parametrize("table", sorted(PLAN_NAMES))
def test_every_constraint_and_index_named_by_the_plan_exists(table: str) -> None:
    assert PLAN_NAMES[table] <= _names(metadata.tables[table])


@pytest.mark.parametrize("table", sorted(PLAN_TABLES))
def test_every_constraint_and_index_has_a_short_explicit_name(table: str) -> None:
    schema_table = metadata.tables[table]
    names = [constraint.name for constraint in schema_table.constraints]
    names += [index.name for index in schema_table.indexes]

    assert None not in names
    assert all(len(str(name).encode()) <= MAX_IDENTIFIER_BYTES for name in names)


@pytest.mark.parametrize("table", sorted(PLAN_TABLES))
def test_every_table_has_a_uuid_id_and_a_creation_time(table: str) -> None:
    columns = metadata.tables[table].c

    assert [column.name for column in metadata.tables[table].primary_key] == ["id"]
    assert isinstance(columns.id.type, sa.Uuid)
    assert columns.id.server_default is None  # generated by the application (UUID v7)
    assert isinstance(columns.created_at.type, sa.DateTime)
    assert columns.created_at.type.timezone


def test_only_the_intents_are_never_updated() -> None:
    # A purchase intent is written once, by unit 3; every other table changes.
    without_updated_at = {
        name for name, table in metadata.tables.items() if "updated_at" not in table.c
    }

    assert without_updated_at == {"purchase_intents"}


def test_money_is_integer_minor_units() -> None:
    amounts = [
        tables.products.c.price_minor,
        tables.orders.c.unit_price_minor,
        tables.orders.c.total_minor,
        tables.payments.c.amount_minor,
    ]

    assert all(isinstance(column.type, sa.BigInteger) for column in amounts)


def test_the_partial_indexes_of_the_plan() -> None:
    assert _partial_index(tables.orders, "uq_orders_pending_buyer_product").unique
    assert _partial_index(tables.payments, "uq_payments_order_id_pending").unique
    assert not _partial_index(tables.orders, "ix_orders_pending_reserved_until").unique
    assert not _partial_index(
        tables.comments, "ix_comments_rejected_session_id_rejection_reason"
    ).unique
    assert not _partial_index(
        tables.processed_webhook_events, "ix_processed_webhook_events_unprocessed_created_at"
    ).unique


def test_available_is_generated_from_the_counters() -> None:
    available = tables.products.c.available

    assert isinstance(available.computed, sa.Computed)
    assert available.computed.persisted
